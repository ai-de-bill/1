/*!
 * \file cpu_debug_check.cpp
 * \brief Functional check of op_kernel/mul_ascend.cpp on the Ascend 910B CPU debug model
 *        (tools/cpudebug of the CANN toolkit). It runs the real kernel entry on the software
 *        simulator and compares the result against the wrap-around int64 product.
 *
 * Build:  test/build_cpu_debug.sh
 * Run:    test/mul_ascend_cpu_check
 */

#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <vector>

#include "mul_ascend_tiling.h"

// REGISTER_TILING_DEFAULT / GET_TILING_DATA are generated by the custom-op build
// (asc_op_compiler/get_op_tiling.py). For the CPU debug run the problem size is injected here.
static uint32_t g_tilingSize = 0;
#define REGISTER_TILING_DEFAULT(tilingStruct)
#define GET_TILING_DATA(var, tilingArg) \
    MulAscendTilingData var;            \
    var.size = g_tilingSize

// Compile the kernel under test into this translation unit so that the anonymous-namespace kernel
// class is visible too.
#include "../op_kernel/mul_ascend.cpp"

#include "tikicpulib.h"

namespace {
constexpr int32_t BLOCK_DIM = 16;   // must match TilingFunc: context->SetBlockDim(16)

uint64_t NextRand(uint64_t& state)
{
    state ^= state << 13;
    state ^= state >> 7;
    state ^= state << 17;
    return state;
}

bool CheckOne(int64_t n, int64_t* x, int64_t* y, int64_t* z, uint64_t& seed, int64_t& badCount, int64_t& firstBad)
{
    for (int64_t i = 0; i < n; ++i) {
        x[i] = static_cast<int64_t>(NextRand(seed));
        y[i] = static_cast<int64_t>(NextRand(seed));
        if ((i % 7) == 0) {           // mix in extremes
            x[i] = (i % 14 == 0) ? INT64_MIN : INT64_MAX;
            y[i] = (i % 14 == 0) ? INT64_MAX : INT64_MIN;
        }
        z[i] = 0;
    }

    uint8_t* workspace = static_cast<uint8_t*>(AscendC::GmAlloc(8));
    uint8_t* tiling = static_cast<uint8_t*>(AscendC::GmAlloc(8));
    g_tilingSize = static_cast<uint32_t>(n);
    ICPU_RUN_KF(mul_ascend, BLOCK_DIM, reinterpret_cast<uint8_t*>(x), reinterpret_cast<uint8_t*>(y),
                reinterpret_cast<uint8_t*>(z), workspace, tiling);
    AscendC::GmFree(workspace);
    AscendC::GmFree(tiling);

    bool ok = true;
    for (int64_t i = 0; i < n; ++i) {
        const int64_t ref = static_cast<int64_t>(static_cast<uint64_t>(x[i]) * static_cast<uint64_t>(y[i]));
        if (z[i] != ref) {
            if (badCount == 0) { firstBad = i; }
            ++badCount;
            ok = false;
        }
    }
    return ok;
}
} // namespace

int main()
{
    const int64_t sizes[] = {1, 2, 3, 4, 5, 7, 15, 16, 17, 63, 255, 256, 257, 511, 512, 513, 1000, 4095, 4096, 4097,
                             65536, 100000};

    uint64_t seed = 0x123456789abcdefULL;
    int64_t badCount = 0;
    int64_t firstBad = -1;
    int failures = 0;

    for (int64_t n : sizes) {
        int64_t* x = static_cast<int64_t*>(AscendC::GmAlloc(static_cast<size_t>(n) * sizeof(int64_t)));
        int64_t* y = static_cast<int64_t*>(AscendC::GmAlloc(static_cast<size_t>(n) * sizeof(int64_t)));
        int64_t* z = static_cast<int64_t*>(AscendC::GmAlloc(static_cast<size_t>(n) * sizeof(int64_t)));
        const bool ok = CheckOne(n, x, y, z, seed, badCount, firstBad);
        printf("n = %8lld  %s\n", static_cast<long long>(n), ok ? "OK" : "FAILED");
        if (!ok) {
            ++failures;
        }
        AscendC::GmFree(x);
        AscendC::GmFree(y);
        AscendC::GmFree(z);
    }

    if (failures == 0) {
        printf("ALL PASSED (%d sizes)\n", static_cast<int>(sizeof(sizes) / sizeof(sizes[0])));
        return 0;
    }
    printf("FAILED: %d sizes, %lld mismatching elements (first at flat index %lld)\n", failures,
           static_cast<long long>(badCount), static_cast<long long>(firstBad));
    return 1;
}
